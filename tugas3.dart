void main() {
  ///menghitung bilangan ganjil 1-20
  //bilangan antara 1-20 dengan rumus angka i+2
  for (int i = 1; i <= 20; i += 2) {
    print(' $i');
  }

  ///menghitung jumlah nama aisyah hanya smpai 4x
  int n = 4;
  while (n > 0) {
    /*hanya print sampai 4x*/
    print('aisyah $n');
    n--;
  }
}
